function createTerminalLine(
  text,
  cssClass = ""
) {
  const line =
    document.createElement("div");

  line.className =
    `terminal-line ${cssClass}`.trim();

  line.textContent = text;

  return line;
}

function appendTerminalLines(
  lines,
  cssClass = ""
) {
  lines.forEach((lineText) => {
    terminalOutput.appendChild(
      createTerminalLine(
        lineText,
        cssClass
      )
    );
  });

  terminalOutput.scrollTop =
    terminalOutput.scrollHeight;
}

function appendCommand(command) {
  terminalOutput.appendChild(
    createTerminalLine(
      `$ ${command}`,
      "terminal-command"
    )
  );
}

function resetTerminal() {
  terminalOutput.innerHTML = "";

  appendTerminalLines(
    terminalContent[currentLanguage].welcome,
    "terminal-muted"
  );
}

function normalizeCommand(command) {
  return command
    .trim()
    .toLowerCase();
}

function executeCommand(rawCommand) {
  const command =
    normalizeCommand(rawCommand);

  if (!command) {
    return;
  }

  appendCommand(command);

  if (command === "clear") {
    terminalOutput.innerHTML = "";
    return;
  }

  const validCommands = [
    "help",
    "about",
    "stack",
    "experience",
    "projects",
    "leadership",
    "languages",
    "contact"
  ];

  if (!validCommands.includes(command)) {
    appendTerminalLines(
      [
        terminalContent[currentLanguage]
          .unknown
      ],
      "terminal-error"
    );

    return;
  }

  appendTerminalLines(
    terminalContent[currentLanguage][command]
  );
}

terminalForm.addEventListener(
  "submit",
  (event) => {
    event.preventDefault();

    const command =
      terminalInput.value;

    executeCommand(command);

    terminalInput.value = "";
    terminalInput.focus();
  }
);

commandShortcuts.forEach((button) => {
  button.addEventListener("click", () => {
    const command =
      button.dataset.command;

    executeCommand(command);

    terminalInput.focus();
  });
});

