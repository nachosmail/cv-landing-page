export function getLocalizedValue(
  value,
  language = "en"
) {
  if (
    value &&
    typeof value === "object" &&
    !Array.isArray(value)
  ) {
    return (
      value[language] ??
      value.en ??
      ""
    );
  }

  return value ?? "";
}

export function getCvData(
  language = "en"
) {
  const safeLanguage =
    language === "es"
      ? "es"
      : "en";

  return {
    language:
      safeLanguage,

    personal: {
      ...cvData.personal,

      location:
        getLocalizedValue(
          cvData.personal.location,
          safeLanguage
        )
    },

    professionalTitle:
      getLocalizedValue(
        cvData.professionalTitle,
        safeLanguage
      ),

    professionalSubtitle:
      getLocalizedValue(
        cvData.professionalSubtitle,
        safeLanguage
      ),

    profile:
      cvData.profile[safeLanguage],

    featuredTechnologies:
      cvData.featuredTechnologies,

    skillGroups:
      cvData.skillGroups.map(
        (group) => ({
          ...group,

          title:
            getLocalizedValue(
              group.title,
              safeLanguage
            )
        })
      ),

    leadershipSkills: {
      title:
        getLocalizedValue(
          cvData.leadershipSkills.title,
          safeLanguage
        ),

      items:
        cvData.leadershipSkills.items[
          safeLanguage
        ]
    },

    experience:
      cvData.experience.map(
        (job) => ({
          ...job,

          location:
            getLocalizedValue(
              job.location,
              safeLanguage
            ),

          role:
            getLocalizedValue(
              job.role,
              safeLanguage
            ),

          alternativeRole:
            job.alternativeRole
              ? getLocalizedValue(
                  job.alternativeRole,
                  safeLanguage
                )
              : "",

          period:
            getLocalizedValue(
              job.period,
              safeLanguage
            ),

          summary:
            getLocalizedValue(
              job.summary,
              safeLanguage
            ),

          achievements:
            job.achievements[
              safeLanguage
            ],

          technologies:
            Array.isArray(
              job.technologies
            )
              ? job.technologies
              : job.technologies[
                  safeLanguage
                ]
        })
      ),

    selectedSolutions:
      cvData.selectedSolutions.map(
        (solution) => ({
          ...solution,

          title:
            getLocalizedValue(
              solution.title,
              safeLanguage
            ),

          description:
            getLocalizedValue(
              solution.description,
              safeLanguage
            )
        })
      ),

    education:
      cvData.education.map(
        (education) => ({
          ...education,

          degree:
            getLocalizedValue(
              education.degree,
              safeLanguage
            ),

          status:
            getLocalizedValue(
              education.status,
              safeLanguage
            )
        })
      ),

    languages:
      cvData.languages.map(
        (item) => ({
          language:
            getLocalizedValue(
              item.language,
              safeLanguage
            ),

          level:
            getLocalizedValue(
              item.level,
              safeLanguage
            )
        })
      ),

    sections:
      Object.fromEntries(
        Object.entries(
          cvData.cvSections
        ).map(
          ([key, value]) => [
            key,
            getLocalizedValue(
              value,
              safeLanguage
            )
          ]
        )
      )
  };
}